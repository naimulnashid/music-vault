// Prints a SQL script that runs docs/fixtures/track-edit.golden.json against
// the real public.apply_track_edit — the third implementation pinned by the
// fixture (alongside trackFields.ts and TrackEdit.kt). Paste the output into
// the Supabase SQL editor; it rolls everything back and ends with
// "track edit golden: N cases passed" or raises listing the failing cases.
//
//   node supabase/tests/track_edit_golden.mjs > /tmp/golden.sql

import { readFileSync } from "node:fs";

const fixture = JSON.parse(
  readFileSync(new URL("../../docs/fixtures/track-edit.golden.json", import.meta.url), "utf8"),
);
const owner = fixture.row.user_id;
const body = JSON.stringify({ row: fixture.row, cases: fixture.cases });
if (body.includes("$fx$")) throw new Error("fixture contains the dollar-quote tag");

// The SQL function's message for each fixture error code.
const messages = {
  not_editable: "field % is not editable",
  empty_title: "title cannot be empty",
  invalid_release_date: "invalid release_date",
  invalid_artwork_key: "invalid artwork_key",
};

process.stdout.write(`-- Generated by supabase/tests/track_edit_golden.mjs — do not edit by hand.
begin;

insert into auth.users (id, email) values ('${owner}', 'golden@vault.test');
set local role authenticated;
set local request.jwt.claims = '{"sub": "${owner}", "role": "authenticated"}';

do $$
declare
  fx jsonb := $fx$${body}$fx$::jsonb;
  messages jsonb := '${JSON.stringify(messages)}'::jsonb;
  cols text[] := array['title', 'artist', 'album', 'genre', 'language', 'country', 'release_date', 'year',
                       'lyrics_text', 'lyrics_synced', 'artwork_key'];
  tid constant uuid := '20000000-0000-4000-8000-0000000000ff';
  c jsonb; e jsonb; start jsonb; want jsonb; got jsonb; col text; err text;
  fails text[] := '{}';
  n int := 0;
begin
  for c in select * from jsonb_array_elements(fx->'cases') loop
    n := n + 1;
    start := (fx->'row') || coalesce(c->'row', '{}'::jsonb);
    delete from public.tracks where id = tid;
    insert into public.tracks
      select * from jsonb_populate_record(null::public.tracks, start || jsonb_build_object(
        'id', tid, 'content_hash', repeat('e', 64), 'file_name', 'golden.flac', 'file_size', 0,
        'duration', 0, 'created_at', now(), 'updated_at', now()));

    err := null;
    begin
      for e in select * from jsonb_array_elements(c->'edits') loop
        perform public.apply_track_edit(tid, e->'patch', (e->>'editedAt')::timestamptz);
      end loop;
    exception when others then
      err := sqlerrm;
    end;

    if c ? 'error' then
      -- the messages double as LIKE patterns ("field % is not editable")
      if err is null or err not like messages->>(c->>'error') then
        fails := fails || format('%s: expected %s, got %s', c->>'name', c->>'error', coalesce(err, 'no error'));
      end if;
      continue;
    end if;
    if err is not null then
      fails := fails || format('%s: unexpected error %s', c->>'name', err);
      continue;
    end if;

    select to_jsonb(t) into got from public.tracks t where id = tid;
    want := start || (c->'expected');
    foreach col in array cols loop
      if (got->col) is distinct from (want->col) then
        fails := fails || format('%s: %s expected %s, got %s', c->>'name', col, want->col, got->col);
      end if;
    end loop;
    -- the edit clock compares as instants (the server writes "+00:00", clients "Z")
    if (select array_agg(k order by k) from jsonb_object_keys(got->'field_edited_at') k)
       is distinct from (select array_agg(k order by k) from jsonb_object_keys(want->'field_edited_at') k)
       or exists (select 1 from jsonb_object_keys(want->'field_edited_at') k
                  where (got->'field_edited_at'->>k)::timestamptz <> (want->'field_edited_at'->>k)::timestamptz) then
      fails := fails || format('%s: field_edited_at expected %s, got %s', c->>'name', want->'field_edited_at', got->'field_edited_at');
    end if;
  end loop;

  if cardinality(fails) > 0 then
    raise exception 'track edit golden failures: %', array_to_string(fails, ' | ');
  end if;
  raise notice 'track edit golden: % cases passed', n;
end $$;

reset role;
rollback;
select 'track edit golden: ${fixture.cases.length} cases passed' as result;
`);
